import json
import time
import random
import asyncio
import re
from typing import Dict, Any, Optional
from utils.logging import get_logger
from .base import BaseLLM

logger = get_logger(__name__)


class MirroredLLM(BaseLLM):
    """
    MirroredLLM - An LLM implementation that mirrors back the received messages

    This LLM implementation logs the received message content and packages it
    according to the format required by model_ailo.py before returning it.
    It doesn't perform any actual language processing, simply mirroring back the input.
    """

    def __init__(self):
        """Initialize MirroredLLM instance"""
        super().__init__()
        self.model_id = "mirrored-llm"
        logger.info("MirroredLLM initialized")

    async def generate_response(self, context: Dict[str, Any], **kwargs) -> Dict[str, Any]:
        """
        Package received context into standard LLM response structure and return it

        Args:
            context: Context dictionary containing message history, etc.
            **kwargs: Additional keyword arguments (ignored in this implementation)

        Returns:
            Dict: Standardized LLM response structure
        """
        try:
            # Log received context
            logger.info("received_context", kwargs_keys=list(kwargs.keys()) if kwargs else [])

            # Extract message history
            messages = context.get("messages", [])
            last_user_message = ""
            message_tag = "[msg]"  # Message separator, consistent with model_ailo.py

            # Log system prompt and user messages
            if messages:
                system_prompt = (
                    messages[0].get("content", "") if messages[0].get("role") == "system" else ""
                )
                user_messages = [msg for msg in messages if msg.get("role") == "user"]

                logger.info(
                    "processing_context",
                    system_prompt_length=len(system_prompt),
                    user_messages_count=len(user_messages),
                )

                # Extract the last user message (if exists)
                if user_messages:
                    last_user_message = user_messages[-1].get("content", "")
                    logger.info(
                        "last_user_message",
                        message=(
                            last_user_message[:200] + "..."
                            if len(last_user_message) > 200
                            else last_user_message
                        ),
                    )

            # Add a small delay to simulate API call
            await asyncio.sleep(1)

            # Extract actual content from the last user message
            # User messages typically include a timestamp, e.g. [2023-01-01 12:00:00]message content
            # We need to remove this timestamp prefix
            cleaned_message = last_user_message
            timestamp_match = re.search(r"^\[.*?\](.*)", last_user_message)
            if timestamp_match:
                cleaned_message = timestamp_match.group(1)

            # If message is empty, use default reply
            if not cleaned_message.strip():
                cleaned_message = "I received an empty message"

            # Build standard response format
            # Here we construct a response format that matches what model_ailo.py expects
            response_data = {
                "thought": f"This is a mirrored reply, I'll return the user's content exactly as received.",
                "is_attack": False,
                "want_reply": True,
                "reply_content": cleaned_message,
                "emotions": {"none": 0},
                "friend_score": 0,
                "romance_score": 0,
                "is_important": False,
                "note": "This is a mirrored reply generated by MirroredLLM",
                "prepared_content": "",
                "is_block": False,
            }

            # If system prompt contains a summary request, add summary field
            if messages and "的对话进行总结概括" in messages[0].get("content", ""):
                response_data["summary"] = f"This is a conversation summary generated by MirroredLLM."
                logger.info("summary_field_added")

            # Serialize to JSON string
            serialized_content = json.dumps(response_data, ensure_ascii=False)

            # Build complete LLM response structure
            response = {
                "id": f"mirror-{random.randint(1000000, 9999999)}",
                "object": "chat.completion",
                "created": int(time.time()),
                "model": self.model_id,
                "choices": [
                    {
                        "index": 0,
                        "message": {"role": "assistant", "content": serialized_content},
                        "logprobs": None,
                        "finish_reason": "stop",
                    }
                ],
                "usage": {
                    "prompt_tokens": len(str(context)) // 4,
                    "completion_tokens": len(serialized_content) // 4,
                    "total_tokens": (len(str(context)) + len(serialized_content)) // 4,
                    "prompt_tokens_details": {"cached_tokens": 0},
                },
            }

            logger.info(
                "response_generated",
                response_id=response["id"],
                response_content=(
                    serialized_content[:200] + "..."
                    if len(serialized_content) > 200
                    else serialized_content
                ),
            )
            return response

        except Exception as e:
            logger.error("generate_response_error", error=str(e), exc_info=True)
            # Return error response instead of None
            return {"error": {"message": str(e), "type": "internal_error", "code": 500}}

    async def validate_response(self, response: Dict[str, Any]) -> tuple[bool, Optional[str]]:
        """
        Validate if response conforms to standard LLM response structure

        Args:
            response: LLM response content

        Returns:
            tuple[bool, Optional[str]]: (is_valid, error_message)
        """
        if "error" in response:
            error_msg = f"API error: {response['error']}"
            logger.error("response_validation_failed", error=error_msg)
            return False, error_msg

        try:
            # Validate required fields
            required_fields = ["id", "object", "created", "model", "choices", "usage"]
            missing_fields = [field for field in required_fields if field not in response]
            if missing_fields:
                logger.warning("missing_required_fields", fields=missing_fields)
                return False, f"Missing required fields: {missing_fields}"

            # Validate choices field
            if not response["choices"] or not isinstance(response["choices"], list):
                logger.warning("invalid_choices_field")
                return False, "Invalid or empty choices field"

            # Validate message field
            choice = response["choices"][0]
            if "message" not in choice or not isinstance(choice["message"], dict):
                logger.warning("missing_message_field")
                return False, "Missing message field in choice"

            if not all(key in choice["message"] for key in ["role", "content"]):
                logger.warning("invalid_message_format")
                return False, "Invalid message format in choice"

            # Validate content is valid JSON
            try:
                content = choice["message"]["content"]
                json.loads(content)
            except json.JSONDecodeError:
                logger.warning("invalid_json_content")
                return False, "Content is not valid JSON"

            logger.info("response_validation_successful")
            return True, None

        except Exception as e:
            logger.error("validation_error", error=str(e), exc_info=True)
            return False, f"Validation error: {str(e)}"
