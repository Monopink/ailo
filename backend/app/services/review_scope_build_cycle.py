"""Build-cycle based reviewer detection for mini-program flows."""

from __future__ import annotations

from dataclasses import dataclass
from datetime import UTC, datetime

from sqlalchemy.ext.asyncio import AsyncSession

from app.enums import ReviewScope
from app.services.system_config import get_config
from app.utils.logging import get_logger

logger = get_logger(__name__)

MP_WEIXIN_REVIEW_DEADLINE_AT_CONFIG_KEY = "mp_weixin_review_deadline_at"
MP_WEIXIN_REVIEW_BUILD_IDS_CONFIG_KEY = "mp_weixin_review_build_ids"
MP_WEIXIN_REVIEW_BUILD_TIME_FROM_CONFIG_KEY = "mp_weixin_review_build_time_from"
MP_WEIXIN_REVIEW_BUILD_TIME_TO_CONFIG_KEY = "mp_weixin_review_build_time_to"


@dataclass(frozen=True)
class ReviewScopeBuildCycleConfig:
    """Normalized runtime config values for review-cycle matching."""

    deadline_at: datetime | None
    build_ids: tuple[str, ...]
    build_time_from: datetime | None
    build_time_to: datetime | None

    @property
    def has_build_id_matcher(self) -> bool:
        return len(self.build_ids) > 0

    @property
    def has_build_time_matcher(self) -> bool:
        return self.build_time_from is not None or self.build_time_to is not None

    @property
    def has_any_matcher(self) -> bool:
        return self.has_build_id_matcher or self.has_build_time_matcher


@dataclass(frozen=True)
class ReviewScopeBuildCycleDecision:
    """Review-scope decision generated by build-cycle matching."""

    review_scope: ReviewScope
    in_review_period: bool
    matched_build_id: bool
    matched_build_time: bool
    build_id_matcher_enabled: bool
    build_time_matcher_enabled: bool

    @property
    def is_limited_scope(self) -> bool:
        return self.review_scope == ReviewScope.MP_WEIXIN_REVIEW


def _parse_optional_utc_datetime(raw_value: object) -> datetime | None:
    if not isinstance(raw_value, str):
        return None
    value = raw_value.strip()
    if value == "":
        return None
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return None
    if parsed.tzinfo is None:
        return parsed.replace(tzinfo=UTC)
    return parsed.astimezone(UTC)


def _normalize_build_id(raw_value: str | None) -> str:
    if not isinstance(raw_value, str):
        return ""
    return raw_value.strip()


def _normalize_build_ids(raw_value: object) -> tuple[str, ...]:
    if not isinstance(raw_value, list):
        return ()
    dedup: list[str] = []
    seen: set[str] = set()
    for item in raw_value:
        if not isinstance(item, str):
            continue
        build_id = _normalize_build_id(item)
        if build_id == "" or build_id in seen:
            continue
        seen.add(build_id)
        dedup.append(build_id)
    return tuple(dedup)


def normalize_client_build_time(raw_value: str | None) -> datetime | None:
    """Parse client build_time and normalize to UTC."""
    return _parse_optional_utc_datetime(raw_value)


async def load_mp_weixin_review_cycle_config(db: AsyncSession) -> ReviewScopeBuildCycleConfig:
    """Load and normalize review-cycle config fields for mp_weixin."""
    deadline_at = _parse_optional_utc_datetime(
        await get_config(db, MP_WEIXIN_REVIEW_DEADLINE_AT_CONFIG_KEY, required=False)
    )
    build_ids = _normalize_build_ids(
        await get_config(db, MP_WEIXIN_REVIEW_BUILD_IDS_CONFIG_KEY, required=False)
    )
    build_time_from = _parse_optional_utc_datetime(
        await get_config(db, MP_WEIXIN_REVIEW_BUILD_TIME_FROM_CONFIG_KEY, required=False)
    )
    build_time_to = _parse_optional_utc_datetime(
        await get_config(db, MP_WEIXIN_REVIEW_BUILD_TIME_TO_CONFIG_KEY, required=False)
    )
    return ReviewScopeBuildCycleConfig(
        deadline_at=deadline_at,
        build_ids=build_ids,
        build_time_from=build_time_from,
        build_time_to=build_time_to,
    )


def _is_in_review_period(config: ReviewScopeBuildCycleConfig, *, now: datetime) -> bool:
    if config.deadline_at is None:
        return False
    return config.deadline_at >= now


def _is_build_id_matched(config: ReviewScopeBuildCycleConfig, *, build_id: str) -> bool:
    if not config.has_build_id_matcher:
        return True
    if build_id == "":
        return False
    return build_id in config.build_ids


def _is_build_time_matched(
    config: ReviewScopeBuildCycleConfig, *, build_time: datetime | None
) -> bool:
    if not config.has_build_time_matcher:
        return True
    if build_time is None:
        return False
    if config.build_time_from is not None and build_time < config.build_time_from:
        return False
    return config.build_time_to is None or build_time <= config.build_time_to


def classify_mp_weixin_review_scope_by_build_cycle(
    *,
    config: ReviewScopeBuildCycleConfig,
    build_id: str | None,
    build_time: str | None,
    now: datetime | None = None,
) -> ReviewScopeBuildCycleDecision:
    """Classify review scope using configured review-cycle build match rules."""
    effective_now = now.astimezone(UTC) if now is not None else datetime.now(UTC)
    effective_build_id = _normalize_build_id(build_id)
    effective_build_time = normalize_client_build_time(build_time)

    in_review_period = _is_in_review_period(config, now=effective_now)
    matched_build_id = _is_build_id_matched(config, build_id=effective_build_id)
    matched_build_time = _is_build_time_matched(config, build_time=effective_build_time)
    matched = (
        in_review_period and config.has_any_matcher and matched_build_id and matched_build_time
    )

    return ReviewScopeBuildCycleDecision(
        review_scope=ReviewScope.MP_WEIXIN_REVIEW if matched else ReviewScope.NON_REVIEW,
        in_review_period=in_review_period,
        matched_build_id=matched_build_id,
        matched_build_time=matched_build_time,
        build_id_matcher_enabled=config.has_build_id_matcher,
        build_time_matcher_enabled=config.has_build_time_matcher,
    )
