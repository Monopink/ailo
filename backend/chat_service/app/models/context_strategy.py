# Protocol defining the interface for context strategies.
# Implemented by ContextStrategy and used by consumers like ModelLily for type checking.
@runtime_checkable
class ContextStrategyProtocol(Protocol):
    """Context strategy protocol for type checking.

    This protocol defines the interface for context strategy objects,
    primarily for their validation capabilities, ensuring that they provide
    a method to validate task-based responses from an LLM.
    """

    def validate_tasks(self, response_content: str) -> "ValidationResult":
        """Validate if response content meets task requirements

        Args:
            response_content: Response content string generated by LLM

        Returns:
            ValidationResult: Validation result object containing validity and error messages
        """
        ...


