@dataclass
class ValidationError:
    """Validation error details"""

    error_type: ValidationErrorType
    field_name: Optional[str] = None
    expected_type: Optional[type] = None
    actual_type: Optional[type] = None
    message: Optional[str] = None


@dataclass
class ValidationResult:
    """Validation result"""

    is_valid: bool = True
    errors: List[ValidationError] = field(default_factory=list)

    def add_error(self, error: ValidationError) -> None:
        """Add error"""
        self.errors.append(error)
        self.is_valid = False

    def get_error_messages(self) -> List[str]:
        """Get all error messages"""
        messages = []
        for error in self.errors:
            if error.message:
                messages.append(error.message)
            elif error.error_type == ValidationErrorType.MISSING_FIELD:
                messages.append(f"Missing required field: {error.field_name}")
            elif error.error_type == ValidationErrorType.INVALID_TYPE:
                messages.append(
                    f"Field '{error.field_name}' has invalid type: expected {error.expected_type}, got {error.actual_type}"
                )
            elif error.error_type == ValidationErrorType.INVALID_VALUE:
                messages.append(f"Field '{error.field_name}' has invalid value")
            elif error.error_type == ValidationErrorType.INVALID_RANGE:
                messages.append(f"Field '{error.field_name}' value is out of valid range")
        return messages


