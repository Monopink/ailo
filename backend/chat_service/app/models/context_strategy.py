class ContextStrategy(ContextStrategyProtocol):
    """Context strategy: Define tasks and validate responses"""

    def __init__(self, include_summary: bool = False, include_thought: bool = True, memory_limit: int = 0):
        """Initialize context strategy

        Args:
            include_thought: Whether to include pre-response thinking task
            include_summary: Whether to include summary task
            memory_limit: Memory limit for conversation summary
        """
        # Basic task list
        self._tasks = [
            TaskType.PRE_RESPONSE_THINKING,
            TaskType.ATTACK_CHECK,
            TaskType.RESPONSE_DECISION,
            TaskType.CONTENT_GENERATION,
            TaskType.EMOTION_SCORING,
            TaskType.FRIEND_SCORING,
            TaskType.ROMANCE_SCORING,
            TaskType.IS_IMPORTANT_CONVERSATION,
            TaskType.CONVERSATION_NOTE,
            TaskType.SCHEDULED_MESSAGE,
            TaskType.BLOCK_USER,
        ]

        # Conditionally remove the thinking task
        if not include_thought:
            self._tasks.remove(TaskType.PRE_RESPONSE_THINKING)

        # Add optional tasks
        if include_summary:
            self._tasks.append(TaskType.CONVERSATION_SUMMARY)

        # Store memory limit for summary task
        self._memory_limit = memory_limit

    @property
    def tasks(self) -> List[TaskType]:
        """Get task list"""
        return self._tasks.copy()

    def get_task_descriptions(self, components: ContextComponents) -> List[str]:
        """Get task description list

        Args:
            components: Context components object
        """
        descriptions = []
        for i, task in enumerate(self._tasks):
            # 特殊处理 CONVERSATION_SUMMARY 任务描述
            if task == TaskType.CONVERSATION_SUMMARY and self._memory_limit > 0:
                desc = f"{i+1}. 请对{components.memory_tag}和所有与对方的对话进行总结概括，字符数不超过{self._memory_limit}字符"
            elif task == TaskType.CONTENT_GENERATION:
                desc = f"{i+1}. {TaskDefinition.get_task_description(task).format(message_tag=components.message_tag)}"
            else:
                desc = f"{i+1}. {TaskDefinition.get_task_description(task)}"
            descriptions.append(desc)
        return descriptions

    def get_response_format(self) -> Dict[str, str]:
        """Get response format"""
        return {
            TaskDefinition.get_response_key(task): TaskDefinition.get_example_value(task)
            for task in self._tasks
        }

    def _fix_and_parse_json(self, json_string: str) -> Dict[str, Any]:
        """
        Tries to fix and parse a JSON string that might be malformed by an LLM.
        - Extracts JSON from markdown code blocks.
        - Removes trailing commas.
        """
        # 1. Extract from markdown block if present, e.g., ```json\n{...}\n```
        match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", json_string, re.DOTALL)
        if match:
            json_string = match.group(1)
        else:
            # If no markdown block, find the first '{' and last '}' as a fallback
            start = json_string.find("{")
            end = json_string.rfind("}")
            if start != -1 and end != -1:
                json_string = json_string[start : end + 1]

        # 2. Remove trailing commas before closing braces/brackets
        # e.g. {"key": "value",} -> {"key": "value"}
        json_string = re.sub(r",\s*([\}\]])", r"\1", json_string)

        # 3. Attempt to parse the cleaned string
        return json.loads(json_string)

    def validate_response(self, response: Dict[str, Any]) -> ValidationResult:
        """Validate response

        Args:
            response: JSON data from LLM response

        Returns:
            ValidationResult: Validation result
        """
        result = ValidationResult()

        # Validate that required fields exist and have correct types
        for task_type in self._tasks:
            response_key = TaskDefinition.get_response_key(task_type)

            # Check required fields
            if TaskDefinition.is_required(task_type) and response_key not in response:
                result.add_error(
                    ValidationError(
                        error_type=ValidationErrorType.MISSING_FIELD,
                        field_name=response_key,
                    )
                )
                continue

            # If field exists, validate its value
            if response_key in response:
                value = response[response_key]
                if not TaskDefinition.validate_field(task_type, value):
                    expected_type = TaskDefinition._task_definitions[task_type]["response_type"]
                    result.add_error(
                        ValidationError(
                            error_type=ValidationErrorType.INVALID_TYPE,
                            field_name=response_key,
                            expected_type=expected_type,
                            actual_type=type(value),
                        )
                    )

                # Perform special validations
                if response_key == "emotions":
                    # Check emotion value range
                    for emotion_type, emotion_score in value.items():
                        if emotion_type != "none" and not (1 <= emotion_score <= 12):
                            result.add_error(
                                ValidationError(
                                    error_type=ValidationErrorType.INVALID_RANGE,
                                    field_name=f"{response_key}.{emotion_type}",
                                    message=f"Emotion score for {emotion_type} must be between 1 and 12",
                                )
                            )

                # Validate score range
                elif response_key in ["friend_score", "romance_score"] and isinstance(value, int):
                    if not (-5 <= value <= 5):
                        result.add_error(
                            ValidationError(
                                error_type=ValidationErrorType.INVALID_RANGE,
                                field_name=response_key,
                                message=f"Field '{response_key}' must be between -5 and 5",
                            )
                        )

        return result

    def validate_tasks(self, response_content: str) -> ValidationResult:
        """Validate if response content meets task requirements

        Args:
            response_content: Response content string generated by LLM

        Returns:
            ValidationResult: Validation result
        """
        try:
            # Parse JSON using the robust helper
            response_data = self._fix_and_parse_json(response_content)

            # Defensively cast types for robustness against LLM formatting errors
            for task_type in self._tasks:
                key = TaskDefinition.get_response_key(task_type)
                if key in response_data:
                    value = response_data[key]
                    expected_type = TaskDefinition._task_definitions[task_type]["response_type"]

                    # Cast string booleans
                    if expected_type is bool and isinstance(value, str):
                        if value.lower() == "true":
                            response_data[key] = True
                        elif value.lower() == "false":
                            response_data[key] = False

                    # Cast string integers
                    elif expected_type is int and isinstance(value, str):
                        try:
                            response_data[key] = int(value)
                        except (ValueError, TypeError):
                            pass  # Let the main validation handle the error

                    # Cast stringified JSON objects
                    elif expected_type is dict and isinstance(value, str):
                        try:
                            response_data[key] = json.loads(value)
                        except json.JSONDecodeError:
                            pass  # Let the main validation handle the error

            result = self.validate_response(response_data)

            # Log validation results after completion
            if result.is_valid:
                logger.info("Task validation successful")
            else:
                error_messages = result.get_error_messages()
                logger.error(f"Task validation failed: {'; '.join(error_messages)}")

            return result
        except json.JSONDecodeError:
            result = ValidationResult()
            result.add_error(
                ValidationError(
                    error_type=ValidationErrorType.INVALID_TYPE,
                    message="Response is not valid JSON",
                )
            )
            logger.error("Task validation failed: Response is not valid JSON")
            return result
        except Exception as e:
            result = ValidationResult()
            result.add_error(
                ValidationError(
                    error_type=ValidationErrorType.INVALID_VALUE,
                    message=f"Error validating tasks: {str(e)}",
                )
            )
            logger.error(f"Task validation failed: Error validating tasks: {str(e)}", exc_info=True)
            return result


def create_context(
    relationship_type: str,
    relationship_level: str,
    components: Optional[ContextComponents] = None,
    include_summary: bool = False,
    include_thought: bool = True,
    memory_limit: int = 1000,
) -> tuple[str, ContextStrategy]:
    """Create context and strategy

    Args:
        relationship_type: Relationship type
        relationship_level: Relationship level
        components: Context components
        include_summary: Whether to include summary task
        include_thought: Whether to include pre-response thinking task
        memory_limit: Memory limit for conversation summary, default 1000

    Returns:
        tuple: (System prompt, Context strategy instance)
    """
    components = components or ContextComponents()

    # Create strategy
    strategy = ContextStrategy(
        include_summary=include_summary, include_thought=include_thought, memory_limit=memory_limit
    )

    # Process emotion data, especially anger emotion
    emotions_text = ""
    has_anger = False
    anger_score = 0

    if components.emotions:
        emotions_parts = []
        for emotion_type, emotion_data in components.emotions.items():
            emotions_parts.append(
                f"{emotion_type}: 级别 {emotion_data.get('emotion_level', 0)}，分数 {emotion_data.get('emotion_score', 0)}"
            )

            # Check if there is anger emotion
            if emotion_type == "anger":
                has_anger = True
                anger_score = emotion_data.get("emotion_score", 0)

        emotions_text = "\n".join(emotions_parts)

    # If there is anger emotion, modify the emotion scoring task
    if has_anger and anger_score > 0:
        # Use TaskDefinition class method to set emotion task description in angry state
        TaskDefinition.set_emotion_anger_description(anger_score)
    else:
        # Reset to default description
        TaskDefinition.reset_emotion_description()

    # Get task descriptions
    task_descriptions = strategy.get_task_descriptions(components)

    # Build complete system prompt
    prompt_parts = [
        # Basic information
        components.format_system_prefix(),
        # Role information
        components.info_tag,
        components.info,
        # Preset relationship style
        components.preset_style_tag,
        components.get_preset_style(relationship_type, relationship_level),
        # Custom style
        components.style_tag,
        components.style,
        # Current emotions
        components.emotion_tag if emotions_text else "",
        emotions_text,
        # Memory and instant context
        components.memory_tag,
        components.memory,
        components.instant_context_tag,
        components.instant_context,
        # Task requirements
        components.task_prefix,
        "\n".join(task_descriptions),
        components.format_prefix,
        json.dumps(strategy.get_response_format(), indent=2, ensure_ascii=False),
        # Suffix
        components.system_suffix,
    ]

    system_prompt = "\n".join(filter(bool, prompt_parts))
    logger.debug("Generated system prompt: %s", system_prompt)

    return system_prompt, strategy
