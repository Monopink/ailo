import asyncio
import json
from typing import Optional

from ..exceptions import LLMAPIError, LLMResponseError, LLMContentError


async def generate_response(self, llm, **kwargs) -> str:
    """
    Generates a response using the provided LLM client.

    Args:
        self: The ModelLily instance (for context).
        llm: The LLM client object.
        **kwargs: Additional keyword arguments to pass to the LLM's generate_response method.

    Returns:
        The content of the generated response as a string.

    Raises:
        LLMResponseError: If the LLM response is invalid.
        LLMAPIError: For any other errors during API communication.
    """
    try:
        # Call LLM API
        llm_response = await llm.generate_response(self.context, **kwargs)
        self.logger.info("llm_response_generated", llm_response=llm_response)

        # Validate LLM API response structure
        is_valid, error_msg = await llm.validate_response(llm_response)
        if not is_valid:
            raise LLMResponseError(f"Invalid LLM API response: {error_msg}")

        # Extract assistant message from response
        assistant_message = llm_response["choices"][0]["message"]
        response_content = assistant_message["content"]
        return response_content

    except LLMResponseError:
        # Re-raise validation errors to be handled by the retry loop
        raise
    except Exception as e:
        # Wrap other exceptions in LLMAPIError
        self.logger.error("generate_response_error", error=str(e), exc_info=True)
        raise LLMAPIError(f"Failed to generate response: {str(e)}")


async def validate_content(self, response: str | None) -> bool:
    """
    Validate response content using the bot's context strategy.

    Args:
        self: The ModelLily instance (for context_strategy_instance).
        response: The response string generated by the LLM.

    Returns:
        True if validation passed.

    Raises:
        LLMContentError: If the content is invalid, not valid JSON, or fails task validation.
    """
    if not response:
        raise LLMContentError("Response is empty")

    try:
        # Use current strategy object
        if not self.context_strategy_instance:
            # If no strategy object, perform basic JSON validation
            self.logger.warning("no_context_strategy_found", message="Performing basic validation")
            try:
                json.loads(response)
                return True
            except json.JSONDecodeError:
                raise LLMContentError("Response is not valid JSON")

        # Use strategy object to validate tasks in response
        validation_result = self.context_strategy_instance.validate_tasks(response)

        if not validation_result.is_valid:
            error_messages = validation_result.get_error_messages()
            error_msg = "; ".join(error_messages)
            raise LLMContentError(f"Task validation failed: {error_msg}")

        return True

    except LLMContentError:
        # Re-raise to be caught by the retry loop
        raise
    except Exception as e:
        self.logger.error("validate_tasks_error", error=str(e), exc_info=True)
        # Wrap other exceptions
        raise LLMContentError(f"Error validating tasks: {str(e)}")


async def get_response_content(self, llm, **kwargs) -> Optional[str]:
    """
    Gets response content from the LLM, with a retry mechanism.

    This function orchestrates the generation and validation of the response.

    Args:
        self: The ModelLily instance (for config and methods).
        llm: The LLM client object.
        **kwargs: Additional keyword arguments to pass to the generate_response function.

    Returns:
        The validated response content as a string, or None if all retries fail.
    """
    response_content = None
    for attempt in range(self.llm_max_retries):
        try:
            # Step 1: Generate response from LLM
            response_content = await generate_response(self, llm, **kwargs)
            self.logger.info("llm_response_generated", attempt=attempt + 1)

            # Step 2: Validate the content of the response
            await validate_content(self, response_content)
            self.logger.info("llm_response_validated", attempt=attempt + 1)

            # If both are successful, break the loop
            return response_content

        except (LLMAPIError, LLMResponseError, LLMContentError) as e:
            self.logger.warning(
                "llm_attempt_failed", attempt=attempt + 1, max_attempts=self.llm_max_retries, error=str(e)
            )
            if attempt + 1 < self.llm_max_retries:
                await asyncio.sleep(self.llm_retry_delay_secs)
            else:
                self.logger.error("llm_all_attempts_failed", retries=self.llm_max_retries)
                return None  # Abort processing
        except Exception as e:
            self.logger.error("llm_unexpected_error", error=str(e), exc_info=True)
            return None  # Abort on unexpected errors
    return None
