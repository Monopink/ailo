const escapeHtml = (value: string): string =>
  value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');

const toRichTextHtml = (markdownLikeText: string): string => {
  const escaped = escapeHtml(markdownLikeText.trim());
  return escaped.replace(/\r?\n/g, '<br/>');
};

